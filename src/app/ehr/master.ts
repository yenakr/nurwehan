export const MAT_MASTER: MatM[] = (() => {
  const out: MatM[] = [];
  const cats = Array.from(new Set(BASE.map(b => b[0])));
  let n = 0;
  BASE.forEach(([cat, base, specs, unit]) => {
    specs.forEach(spec => {
      n += 1;
      const name = spec ? (/^\d+(\.\d+)?(mL|Fr|G|cm|μm)$/.test(spec) ? `${base} ${spec}` : `${base} (${spec})`) : base;
      out.push({ name, cat, spec, unit, code: `M${String(cats.indexOf(cat) + 1).padStart(2, '0')}${String(n).padStart(4, '0')}` });
    });
  });
  return out;
})();
export const MAT_CATS = Array.from(new Set(MAT_MASTER.map(m => m.cat)));

