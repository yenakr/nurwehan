// 처방의 경로·횟수에서 용법코드를 유추 (경구약: 1일 n회 식후 → nP, 주사: 경로 그대로)
export function usageOf(r: Record<string, string | undefined>): string {
  const route = (r.route || '').trim();
  if (!route) return '';
  if (r.usage) return r.usage;
  const n = Number((r.cnt || '').replace(/[^0-9]/g, '')) || 0;
  if (/^PO$/i.test(route)) {
    if (r.pri === 'PRN') return 'PRN';
    if (r.pri === 'STAT' || r.pri === 'UD') return 'UD';
    return n === 1 ? 'M' : n >= 2 && n <= 4 ? `${n}P` : 'PO';
  }
  return route;
}
